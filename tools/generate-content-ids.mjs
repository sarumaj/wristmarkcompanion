#!/usr/bin/env node
// Generates watch/source/MarkerContent.mc, the marker IDs the watch steps through:
// those viewer/public/content.json gives a model, so that every marker the watch
// shows has one. A model added to content.json reaches the watch with this.
//
//   node tools/generate-content-ids.mjs           write the file
//   node tools/generate-content-ids.mjs --check   fail if it is stale

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT = join(ROOT, "viewer/public/content.json");
const OUTPUT = join(ROOT, "watch/source/MarkerContent.mc");
// The watch's table holds DICT_4X4_50's codes (tools/generate-dictionary.mjs).
const COUNT = 50;

function fail(message) {
  console.error(`generate-content-ids: ${message}`);
  process.exit(1);
}

let markers;
try {
  markers = JSON.parse(readFileSync(CONTENT, "utf8")).markers;
} catch (error) {
  fail(`cannot read ${CONTENT}: ${error.message}`);
}
const ids = Object.keys(markers ?? {})
  .map(Number)
  .sort((a, b) => a - b);
if (ids.length === 0) {
  fail(`${CONTENT} maps no marker`);
}
const wrong = ids.filter((id) => !Number.isInteger(id) || id < 0 || id >= COUNT);
if (wrong.length) {
  fail(`IDs outside 0-${COUNT - 1} in ${CONTENT}: ${wrong.join(", ")}`);
}

const lines = [];
for (let i = 0; i < ids.length; i += 16) {
  lines.push(`        ${ids.slice(i, i + 16).join(", ")}${i + 16 < ids.length ? "," : ""}`);
}
const text = `// Generated by tools/generate-content-ids.mjs from viewer/public/content.json.
// Do not edit; regenerate with:
//   node tools/generate-content-ids.mjs
// CI fails when this file differs from what the script writes.

import Toybox.Lang;

//! The marker IDs the viewer has a model for, ascending: the ones the watch shows.
module MarkerContent {
    const IDS = [
${lines.join("\n")}
    ] as Array<Number>;
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUTPUT, "utf8");
  } catch {
    // Missing: stale.
  }
  if (current !== text) {
    fail(`${OUTPUT} is stale: run node tools/generate-content-ids.mjs`);
  }
  console.log(`${OUTPUT} is up to date (${ids.length} IDs)`);
} else {
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${OUTPUT}: ${ids.length} IDs`);
}
