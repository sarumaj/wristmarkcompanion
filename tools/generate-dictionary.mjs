#!/usr/bin/env node
// Generates watch/source/MarkerDictionary.mc, the watch's marker table, from the
// dictionary data of the detection library the viewer uses (js-aruco2, pinned in
// viewer/package-lock.json), so that both sides use the exact same bit patterns.
//
//   npm ci --prefix viewer && node tools/generate-dictionary.mjs           write the file
//   npm ci --prefix viewer && node tools/generate-dictionary.mjs --check   fail if it is stale
//
// The dictionary is OpenCV's DICT_4X4_50: the first 50 codes of DICT_4X4_1000
// (OpenCV builds both from the same byte table), which js-aruco2 ships as
// ARUCO_4X4_1000. See docs/dev/decisions/002-marker-dictionary.md.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LIBRARY = join(ROOT, "viewer/node_modules/js-aruco2");
const SOURCE = join(LIBRARY, "src/dictionaries/aruco_4x4_1000.js");
const OUTPUT = join(ROOT, "watch/source/MarkerDictionary.mc");
const COUNT = 50;
const SIZE = 4;
// OpenCV's DICT_4X4_50 corrects 1 bit, so its codes are at least 3 bits apart
// in every rotation (aruco_dictionary.cpp: maxCorrectionBits (4-1)/2).
const MIN_DISTANCE = 3;

function fail(message) {
  console.error(`generate-dictionary: ${message}`);
  process.exit(1);
}

function read(path) {
  try {
    return readFileSync(path, "utf8");
  } catch (error) {
    fail(`cannot read ${path} (${error.code}); run npm ci --prefix viewer first`);
  }
}

const version = JSON.parse(read(join(LIBRARY, "package.json"))).version;
const source = read(SOURCE);

// The data is parsed, not run: the file is a plain object literal of byte pairs.
const license = source.match(/^\/\*[\s\S]*?\*\//);
const bits = source.match(/nBits:\s*(\d+)/);
const list = source.match(/codeList:\s*(\[[\s\S]*?\]\])/);
if (!license || !bits || !list) {
  fail(`${SOURCE} no longer has the expected license comment, nBits and codeList`);
}
if (Number(bits[1]) !== SIZE * SIZE) {
  fail(`expected ${SIZE * SIZE} bits per code, the library has ${bits[1]}`);
}
const pairs = JSON.parse(list[1]);
if (pairs.length < COUNT) {
  fail(`expected at least ${COUNT} codes, the library has ${pairs.length}`);
}

// As js-aruco2's Dictionary._bytes2bin reads them: each byte's bits, most
// significant first, are the cells row by row from the top left; 1 is white.
const codes = pairs.slice(0, COUNT).map((pair, id) => {
  if (pair.length !== 2 || pair.some((byte) => !Number.isInteger(byte) || byte < 0 || byte > 255)) {
    fail(`code ${id} is not two bytes: ${JSON.stringify(pair)}`);
  }
  return pair[0] * 256 + pair[1];
});

function grid(code) {
  return Array.from({ length: SIZE }, (_, row) =>
    Array.from({ length: SIZE }, (_, col) => (code >> (SIZE * SIZE - 1 - (row * SIZE + col))) & 1),
  );
}

function rotate(cells) {
  return cells.map((_, row) => cells.map((line) => line[row]).reverse());
}

function distance(a, b) {
  return a.flat().reduce((sum, bit, i) => sum + (bit !== b.flat()[i] ? 1 : 0), 0);
}

// Every pair of codes, in every rotation, and each code against its own
// rotations (the detector tries all four).
let minimum = Infinity;
codes.forEach((code, i) => {
  let turned = grid(code);
  for (let turn = 1; turn < 4; turn++) {
    turned = rotate(turned);
    minimum = Math.min(minimum, distance(grid(code), turned));
  }
  for (let j = i + 1; j < codes.length; j++) {
    let other = grid(codes[j]);
    for (let turn = 0; turn < 4; turn++) {
      minimum = Math.min(minimum, distance(grid(code), other));
      other = rotate(other);
    }
  }
});
if (minimum < MIN_DISTANCE) {
  fail(`codes are only ${minimum} bits apart, expected at least ${MIN_DISTANCE}`);
}

const rows = [];
for (let i = 0; i < codes.length; i += 10) {
  rows.push(`        ${codes.slice(i, i + 10).join(", ")}${i + 10 < codes.length ? "," : ""}`);
}

const output = `// Generated by tools/generate-dictionary.mjs from js-aruco2 ${version}
// (src/dictionaries/aruco_4x4_1000.js). Do not edit; regenerate with:
//   npm ci --prefix viewer && node tools/generate-dictionary.mjs
// CI fails when this file differs from what the script writes.
//
// The codes are OpenCV's, under the license below, which js-aruco2 ships with them:
//
${license[0]
  .replace(/^\/\*\s*\n?/, "")
  .replace(/\s*\*\/$/, "")
  .split("\n")
  .map((line) => `// ${line}`.trimEnd())
  .join("\n")}

import Toybox.Lang;

module MarkerDictionary {
    // Cells per side of the data area, inside the one cell wide black border.
    const SIZE = ${SIZE};

    // OpenCV DICT_4X4_50: entry i is marker ID i. Bit 15 is the top left cell,
    // then row by row to bit 0 at the bottom right; 1 is white, 0 black.
    // Codes are at least ${minimum} bits apart in every rotation.
    // Decimal, not hex: the Monkey C reference documents decimal literals and
    // typed array literals (https://developer.garmin.com/connect-iq/monkey-c/containers/).
    const CODES = [
${rows.join("\n")}
    ] as Array<Number>;
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUTPUT, "utf8");
  } catch {
    fail(`${OUTPUT} is missing; run node tools/generate-dictionary.mjs`);
  }
  if (current !== output) {
    fail(`${OUTPUT} is stale; run node tools/generate-dictionary.mjs and commit it`);
  }
  console.log(`${OUTPUT} is up to date (js-aruco2 ${version}, ${COUNT} codes, minimum distance ${minimum})`);
} else {
  writeFileSync(OUTPUT, output);
  console.log(`wrote ${OUTPUT} (js-aruco2 ${version}, ${COUNT} codes, minimum distance ${minimum})`);
}
