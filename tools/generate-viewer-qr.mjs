#!/usr/bin/env node
// Generates watch/source/ViewerQr.mc, the QR code the watch's Viewers screen shows: the
// viewer's address, the origin of the relay the watch talks to (Link.RELAY), so that a
// phone's camera opens the viewer. Encoded by the qrcode package (the viewer's dev
// dependencies: npm ci in viewer/ first) in upper case, which QR's alphanumeric mode
// holds in a smaller code than bytes (25 modules a side instead of 29); a URL's scheme
// and host are the same in either case.
//
//   node tools/generate-viewer-qr.mjs           write the file
//   node tools/generate-viewer-qr.mjs --check   fail if it is stale

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LINK = join(ROOT, "watch/source/Link.mc");
const OUTPUT = join(ROOT, "watch/source/ViewerQr.mc");
// M: 15% of the code may be lost (a reflection, a finger) and it still reads.
const LEVEL = "M";

function fail(message) {
  console.error(`generate-viewer-qr: ${message}`);
  process.exit(1);
}

let QRCode;
try {
  QRCode = createRequire(join(ROOT, "viewer/package.json"))("qrcode");
} catch {
  fail("the qrcode package is missing: run npm ci in viewer/ first");
}

const relay = readFileSync(LINK, "utf8").match(/const RELAY = "(https:\/\/[^/"]+)\//)?.[1];
if (!relay) fail(`no const RELAY = "https://<host>/..." in ${LINK}`);
const address = `${relay.toUpperCase()}/`;

const code = QRCode.create([{ data: address, mode: "alphanumeric" }], { errorCorrectionLevel: LEVEL });
const size = code.modules.size;
if (size > 31) fail(`${size} modules a side: more than a Number's bits hold`);
// Each row as a Number: bit size - 1 is the left module; 1 is dark.
const rows = [];
for (let row = 0; row < size; row++) {
  let bits = 0;
  for (let col = 0; col < size; col++) bits = bits * 2 + (code.modules.get(row, col) ? 1 : 0);
  rows.push(`0x${bits.toString(16).padStart(8, "0")}`);
}
const lines = [];
for (let i = 0; i < rows.length; i += 6) {
  lines.push(`        ${rows.slice(i, i + 6).join(", ")}${i + 6 < rows.length ? "," : ""}`);
}

const text = `// Generated by tools/generate-viewer-qr.mjs from Link.RELAY's origin.
// Do not edit; regenerate with:
//   node tools/generate-viewer-qr.mjs
// CI fails when this file differs from what the script writes.

import Toybox.Lang;

//! The QR code of the viewer's address, ${address} (level ${LEVEL}, version ${code.version}).
module ViewerQr {
    //! Modules a side.
    const SIZE = ${size};
    //! A row each, top to bottom: bit SIZE - 1 is the left module; 1 is dark.
    const ROWS = [
${lines.join("\n")}
    ] as Array<Number>;
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUTPUT, "utf8");
  } catch {
    // Missing: stale.
  }
  if (current !== text) fail(`${OUTPUT} is stale: run node tools/generate-viewer-qr.mjs`);
  console.log(`${OUTPUT} is up to date (${address})`);
} else {
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${OUTPUT}: ${address}, ${size}x${size}`);
}
