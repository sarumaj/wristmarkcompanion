#!/usr/bin/env node
// The devices the app is built for (docs/dev/watch.md#devices): every one whose Connect IQ can
// run it, watches, bike computers and handhelds alike, from the SDK's device files, written down in watch/devices.json; and from
// that list the manifest's <iq:products> and watch/devices.jungle, which gives each device
// the launcher icon of its size (tools/generate-icon.mjs draws them).
//
//   node tools/generate-devices.mjs                       write the manifest and the jungle
//   node tools/generate-devices.mjs --sdk <Devices dir>   also write devices.json from the SDK
//   node tools/generate-devices.mjs --check [--sdk ...]   fail if one is stale
//
// The SDK's device files are only where the SDK is installed (CI's watch job, on anvil:
// docs/dev/ci.md); without --sdk the list is taken as committed.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LIST = join(ROOT, "watch/devices.json");
const MANIFEST = join(ROOT, "watch/manifest.xml");
const JUNGLE = join(ROOT, "watch/devices.jungle");
// What the app needs of a device: the manifest's minApiLevel, and room for the app (its
// code, the marker table and the control channel's buffers; the D2 Mach 1 gives 768 KB).
const MIN_API = "3.3.0";
const MIN_MEMORY = 128 * 1024;
// The launcher icon in watch/resources (the D2 Mach 1's size); others get their own.
export const BASE_ICON = "60x60";

function fail(message) {
  console.error(`generate-devices: ${message}`);
  process.exit(1);
}

const newer = (a, b) => {
  const [x, y] = [a, b].map((v) => v.split(".").map(Number));
  for (let i = 0; i < 3; i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) > (y[i] ?? 0);
  return false;
};
const atLeast = (version, minimum) => version === minimum || newer(version, minimum);

// A device from its compiler.json: what the list keeps of it, and why it's left out.
function device(id, json) {
  const watchApp = (json.appTypes ?? []).find((type) => type.type === "watchApp");
  // The newest Connect IQ of its firmware versions, or the API level of its group.
  const group = (json.deviceGroup ?? "").match(/(\d+\.\d+(?:\.\d+)?)/)?.[1];
  const versions = [...(json.partNumbers ?? []).map((part) => part.connectIQVersion), group].filter(Boolean);
  const api = versions.reduce((a, b) => (newer(b, a) ? b : a), "0.0.0");
  const icon = json.launcherIcon ? `${json.launcherIcon.width}x${json.launcherIcon.height}` : null;
  const deviceId = json.deviceId ?? id;
  const entry = { id: deviceId, name: json.displayName ?? id, family: json.deviceFamily ?? "", api, icon };
  let skip = null;
  if (!watchApp) skip = "no watch apps";
  else if (!atLeast(api, MIN_API)) skip = `Connect IQ ${api}`;
  else if (watchApp.memoryLimit < MIN_MEMORY) skip = `${watchApp.memoryLimit / 1024} KB for a watch app`;
  else if (!icon) skip = "no launcher icon size";
  return { entry: { ...entry, memory: watchApp?.memoryLimit ?? 0 }, skip };
}

function fromSdk(directory) {
  if (!existsSync(directory)) fail(`no device files at ${directory}`);
  const kept = [];
  const skipped = [];
  for (const id of readdirSync(directory).sort()) {
    const file = join(directory, id, "compiler.json");
    if (!existsSync(file)) continue;
    const json = JSON.parse(readFileSync(file, "utf8"));
    if (kept.length + skipped.length === 0 && !json.appTypes) {
      fail(`${file} has no appTypes; its keys: ${Object.keys(json).join(", ")}`);
    }
    const { entry, skip } = device(id, json);
    if (skip) skipped.push(`${entry.id}: ${skip}`);
    else kept.push(entry);
  }
  console.log(`${kept.length} devices kept, ${skipped.length} left out:`);
  for (const line of skipped) console.log(`  ${line}`);
  return kept;
}

function manifest(devices) {
  const text = readFileSync(MANIFEST, "utf8");
  const products = devices.map((d) => `            <iq:product id="${d.id}"/>`).join("\n");
  const next = text.replace(/(<iq:products>\n)[\s\S]*?(\n\s*<\/iq:products>)/, `$1${products}$2`);
  if (next === text && !text.includes(products)) fail("no <iq:products> in watch/manifest.xml");
  return next;
}

function jungle(devices) {
  const lines = devices
    .filter((d) => d.icon !== BASE_ICON)
    .map((d) => `${d.id}.resourcePath = $(${d.id}.resourcePath);resources-launcher-${d.icon}`);
  return [
    "# Generated by tools/generate-devices.mjs from watch/devices.json: each device whose",
    `# launcher icon isn't ${BASE_ICON} (resources/) gets the one of its size (tools/generate-icon.mjs).`,
    ...lines,
    "",
  ].join("\n");
}

const args = process.argv.slice(2);
const check = args.includes("--check");
const sdk = args.includes("--sdk") ? args[args.indexOf("--sdk") + 1] : null;

let devices = JSON.parse(readFileSync(LIST, "utf8"));
const outputs = [];
if (sdk) {
  const found = fromSdk(sdk);
  outputs.push([LIST, `${JSON.stringify(found, null, 1)}\n`]);
  devices = found;
}
outputs.push([MANIFEST, manifest(devices)], [JUNGLE, jungle(devices)]);

let stale = false;
for (const [file, content] of outputs) {
  const name = file.slice(ROOT.length + 1);
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (current === content) continue;
  if (check) {
    stale = true;
    console.error(`${name} is stale: run node tools/generate-devices.mjs${sdk ? " --sdk <Devices>" : ""}`);
    // The list the SDK gives, in full, to copy from the log where the SDK is out of reach.
    if (file === LIST) console.error(content);
  } else {
    writeFileSync(file, content);
    console.log(`wrote ${name}`);
  }
}
if (stale) process.exit(1);
