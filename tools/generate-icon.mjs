#!/usr/bin/env node
// Generates the icons, all of them marker 0 of the watch's table
// (watch/source/MarkerDictionary.mc) in a cell of white quiet zone, as MarkerView
// draws it:
//
// - watch/resources/drawables/launcher_icon.png: the watch app's launcher icon,
//   60x60, the D2 Mach 1's size (launcherIcon in the device's compiler.json of the
//   Connect IQ SDK), on black like the app's screen; and one for each other size the
//   devices of watch/devices.json need, in watch/resources-launcher-<w>x<h>/
//   (watch/devices.jungle gives each device its own, tools/generate-devices.mjs);
// - docs/dev/store-assets/icon-500.png and icon-128.png: the store's icon and its
//   optional on-device icon (Garmin's Connect IQ brand guidelines: 500x500 and
//   128x128, sRGB, 10 px of padding, no black or transparent background, no text).
//   Their blue, #0055AA, is in the 64-color palette the guidelines ask for on
//   memory-in-pixel displays, so one icon serves both kinds.
// - fastlane/metadata/android/en-US/images/icon.png: the Android app's store icon, for
//   F-Droid and Google Play (512x512, the marker well inside the circle Play's mask may cut
//   it to; docs/dev/google-play.md).
//
//   node tools/generate-icon.mjs           write the files
//   node tools/generate-icon.mjs --check   fail if one is stale
//
// PNGs written with node:zlib, so nothing is installed.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TABLE = join(ROOT, "watch/source/MarkerDictionary.mc");
const DATA = 4;
const BLACK = [0, 0, 0];
const WHITE = [255, 255, 255];
const STORE_BLUE = [0x00, 0x55, 0xaa];

// Each icon: its size (width, and height where it differs), the cell size of the 8x8
// grid (marker and quiet zone), and the color around it.
const ICONS = [
  { path: "watch/resources/drawables/launcher_icon.png", size: 60, cell: 7, background: BLACK },
  { path: "docs/dev/store-assets/icon-500.png", size: 500, cell: 42, background: STORE_BLUE },
  { path: "docs/dev/store-assets/icon-128.png", size: 128, cell: 11, background: STORE_BLUE },
  // RGBA (all opaque): Play asks for a 32-bit PNG.
  { path: "fastlane/metadata/android/en-US/images/icon.png", size: 512, cell: 40, background: STORE_BLUE, alpha: true },
];
// The other launcher sizes: as large a cell as the shorter side holds.
const BASE_LAUNCHER = "60x60";
const DRAWABLES = `<!-- Generated by tools/generate-icon.mjs: marker 0, this size's launcher icon. -->
<drawables>
    <bitmap id="LauncherIcon" filename="launcher_icon.png"/>
</drawables>
`;
const launchers = [
  ...new Set(JSON.parse(readFileSync(join(ROOT, "watch/devices.json"), "utf8")).map((device) => device.icon)),
]
  .filter((size) => size !== BASE_LAUNCHER)
  .sort();
for (const name of launchers) {
  const [width, height] = name.split("x").map(Number);
  const dir = `watch/resources-launcher-${name}/drawables`;
  ICONS.push({ path: `${dir}/launcher_icon.png`, size: width, height, cell: Math.floor(Math.min(width, height) / 8), background: BLACK });
  ICONS.push({ path: `${dir}/drawables.xml`, text: DRAWABLES });
}

function fail(message) {
  console.error(`generate-icon: ${message}`);
  process.exit(1);
}

const codes = readFileSync(TABLE, "utf8").match(/const CODES = \[([\d,\s]+)\]/);
if (!codes) fail(`no CODES table in ${TABLE}`);
const code = Number(codes[1].split(",")[0]);

// Cell (row, col) of the 8x8 grid: the quiet zone (white), the marker's black
// border, and the data, bit 15 at the top left, row by row; 1 is white.
function white(row, col) {
  if (row === 0 || col === 0 || row === 7 || col === 7) return true;
  if (row === 1 || col === 1 || row === 6 || col === 6) return false;
  const bit = DATA * DATA - 1 - ((row - 2) * DATA + (col - 2));
  return ((code >> bit) & 1) === 1;
}

const CRC = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buffer) {
  let c = 0xffffffff;
  for (const byte of buffer) c = CRC[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

function render({ size, height = size, cell, background, alpha = false }) {
  const width = size;
  const left = Math.floor((width - 8 * cell) / 2);
  const top = Math.floor((height - 8 * cell) / 2);
  if (left < 0 || top < 0) fail(`a ${cell}-pixel cell does not fit ${width}x${height} pixels`);
  const rows = [];
  for (let y = 0; y < height; y++) {
    const channels = alpha ? 4 : 3;
    const row = Buffer.alloc(1 + channels * width, 255); // filter byte, then RGB(A) per pixel
    row[0] = 0;
    for (let x = 0; x < width; x++) {
      const r = Math.floor((y - top) / cell);
      const c = Math.floor((x - left) / cell);
      const inside = y >= top && x >= left && r < 8 && c < 8;
      const color = inside ? (white(r, c) ? WHITE : BLACK) : background;
      row.set(color, 1 + channels * x);
    }
    rows.push(row);
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8; // bit depth
  header[9] = alpha ? 6 : 2; // RGBA or RGB
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", header),
    chunk("IDAT", deflateSync(Buffer.concat(rows), { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const check = process.argv.includes("--check");
for (const icon of ICONS) {
  const file = join(ROOT, icon.path);
  const png = icon.text === undefined ? render(icon) : Buffer.from(icon.text);
  if (check) {
    let current;
    try {
      current = readFileSync(file);
    } catch {
      fail(`${icon.path} is missing: run node tools/generate-icon.mjs`);
    }
    if (!current.equals(png)) fail(`${icon.path} is stale: run node tools/generate-icon.mjs`);
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, png);
    console.log(`wrote ${icon.path} (${png.length} bytes)`);
  }
}

// A launcher directory no device needs any more.
for (const entry of readdirSync(join(ROOT, "watch"))) {
  const size = entry.match(/^resources-launcher-(.+)$/)?.[1];
  if (size && !launchers.includes(size)) fail(`watch/${entry} is for no device of watch/devices.json: remove it`);
}
