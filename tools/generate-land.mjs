#!/usr/bin/env node
// Generates viewer/public/js/land.js, the globe's land and sea: a 1-degree grid,
// one bit per cell (land 1), from Natural Earth's 1:110m land polygons, which are
// in the public domain (https://www.naturalearthdata.com/about/terms-of-use/).
//
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson
//   node tools/generate-land.mjs ne_110m_land.geojson
//
// The download isn't kept in the repository; the output (about 11 KB) is.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "../viewer/public/js/land.js");
const WIDTH = 360;
const HEIGHT = 180;

const source = process.argv[2];
if (!source) {
  console.error("usage: node tools/generate-land.mjs ne_110m_land.geojson");
  process.exit(1);
}
const features = JSON.parse(readFileSync(source, "utf8")).features;
const rings = features.flatMap(({ geometry }) =>
  geometry.type === "Polygon" ? geometry.coordinates : geometry.coordinates.flat(),
);
if (rings.length === 0) {
  console.error(`generate-land: no polygons in ${source}`);
  process.exit(1);
}

// Even-odd rule over every ring: holes (lakes in the outline) come out as sea.
function land(lon, lat) {
  let inside = false;
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

// Row 0 is the north (89.5 degrees), column 0 the date line's west side (-179.5).
const bits = new Uint8Array((WIDTH * HEIGHT) / 8);
let count = 0;
for (let row = 0; row < HEIGHT; row++) {
  for (let col = 0; col < WIDTH; col++) {
    if (land(col - 179.5, 89.5 - row)) {
      const cell = row * WIDTH + col;
      bits[cell >> 3] |= 0x80 >> (cell & 7);
      count++;
    }
  }
}

writeFileSync(
  OUT,
  `// Generated by tools/generate-land.mjs from Natural Earth's 1:110m land (public
// domain): ${WIDTH}x${HEIGHT} cells of one degree, one bit each (land 1), row 0 at the north,
// column 0 at 180 degrees west, base64. Don't edit; run the generator.
export const LAND = {
  width: ${WIDTH},
  height: ${HEIGHT},
  bits: "${Buffer.from(bits).toString("base64")}",
};
`,
);
console.log(`wrote ${OUT}: ${((100 * count) / (WIDTH * HEIGHT)).toFixed(1)}% of the cells land`);
