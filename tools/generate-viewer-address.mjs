#!/usr/bin/env node
// Generates watch/source/ViewerAddress.mc: the viewer's address the watch app is built
// for (docs/dev/watch.md#the-viewers-address), its relay (Link) and the QR code of it that
// the Viewers screen shows, so that a phone's camera opens the viewer. The address is
// WRISTMARK_ORIGIN, by default the homelab's deployment (DEFAULT_ORIGIN). The code is
// made by the qrcode package (the viewer's dev dependencies: npm ci in viewer/ first)
// in upper case, which QR's alphanumeric mode holds in a smaller code than bytes (25
// modules a side instead of 29 for the default); a URL's scheme and host are the same
// in either case.
//
//   node tools/generate-viewer-address.mjs           write the file
//   node tools/generate-viewer-address.mjs --check   fail if it is stale
//   WRISTMARK_ORIGIN=https://wristmark.example.org node tools/generate-viewer-address.mjs
//
// The committed file is the default's (CI checks it); tools/build-watch.sh writes
// another origin's for its build and puts the committed one back.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(ROOT, "watch/source/ViewerAddress.mc");
const DEFAULT_ORIGIN = "https://wristmark.apps.ciepiela.org";
// M: 15% of the code may be lost (a reflection, a finger) and it still reads.
const LEVEL = "M";

function fail(message) {
  console.error(`generate-viewer-address: ${message}`);
  process.exit(1);
}

const origin = process.env.WRISTMARK_ORIGIN || DEFAULT_ORIGIN;
// An origin alone: https, a host, perhaps a port; the viewer and its relay at its root.
if (!/^https:\/\/[a-z0-9.-]+(:\d+)?$/.test(origin)) {
  fail(`WRISTMARK_ORIGIN must be https://<host>[:port], lower case, no path: ${origin}`);
}
const address = `${origin.toUpperCase()}/`;

let QRCode;
try {
  QRCode = createRequire(join(ROOT, "viewer/package.json"))("qrcode");
} catch {
  fail("the qrcode package is missing: run npm ci in viewer/ first");
}
const code = QRCode.create([{ data: address, mode: "alphanumeric" }], { errorCorrectionLevel: LEVEL });
const size = code.modules.size;
if (size > 31) fail(`${origin}: ${size} modules a side, more than a Number's bits hold`);
// Each row as a Number: bit size - 1 is the left module; 1 is dark.
const rows = [];
for (let row = 0; row < size; row++) {
  let bits = 0;
  for (let col = 0; col < size; col++) bits = bits * 2 + (code.modules.get(row, col) ? 1 : 0);
  rows.push(`0x${bits.toString(16).padStart(8, "0")}`);
}
const lines = [];
for (let i = 0; i < rows.length; i += 6) {
  lines.push(`        ${rows.slice(i, i + 6).join(", ")}${i + 6 < rows.length ? "," : ""}`);
}

const text = `// Generated by tools/generate-viewer-address.mjs for ${origin}.
// Do not edit; regenerate with:
//   node tools/generate-viewer-address.mjs
// CI fails when the committed file differs from what the script writes by default.

import Toybox.Lang;

//! The viewer's address the app is built for (WRISTMARK_ORIGIN), and its QR code.
module ViewerAddress {
    const ORIGIN = "${origin}";
    //! The control channel's relay, on the viewer's origin.
    const RELAY = "${origin}/relay/v1";
    //! The QR code of ${address} (level ${LEVEL}, version ${code.version}): modules a side.
    const QR_SIZE = ${size};
    //! A row each, top to bottom: bit QR_SIZE - 1 is the left module; 1 is dark.
    const QR_ROWS = [
${lines.join("\n")}
    ] as Array<Number>;
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUTPUT, "utf8");
  } catch {
    // Missing: stale.
  }
  if (current !== text) fail(`${OUTPUT} is stale: run node tools/generate-viewer-address.mjs`);
  console.log(`${OUTPUT} is up to date (${origin})`);
} else {
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${OUTPUT}: ${origin}, QR code ${size}x${size}`);
}
